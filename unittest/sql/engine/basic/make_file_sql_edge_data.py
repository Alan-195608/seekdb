#!/usr/bin/env python3
"""Write the byte-exact edge-case fixtures for the file SQL mysqltest.

Run from the repository root:
    python3 unittest/sql/engine/basic/make_file_sql_edge_data.py

The output directory is overwritten in place; it holds nothing but the fixtures
generated by this script.
"""
import os

TARGET = os.path.join(
    "tools", "deploy", "mysql_test", "test_suite", "file_sql", "data_edge")

FIXTURES = {
    # A leap day in a leap year is a valid DATE.
    "date_leap_ok.csv": b"d\n2024-02-29\n",
    # 2026 is not a leap year, so this day does not exist.  It must not become
    # a DATE; the value stays ordinary text.
    "date_leap_bad.csv": b"d\n2026-02-29\n",
    # Month 13 does not exist either.
    "date_month_bad.csv": b"d\n2026-13-01\n",
    # An ordinary date.
    "date_ok.csv": b"d\n2026-08-01\n",
    # A datetime without sub-second parts.
    "datetime_plain.csv": b"t\n2026-08-01 10:11:12\n",
    # A datetime that carries sub-second parts; the precision must survive.
    "datetime_frac.csv": b"t\n2026-08-01 10:11:12.123456\n",
    # A datetime whose fractional part is followed by ordinary text.  The
    # suffix must not be swallowed: the value stays text.
    "datetime_suffix.csv": b"t\n2026-08-01 10:11:12.1junk\n",
    # The ISO 8601 separator is accepted as well.
    "datetime_t.csv": b"t\n2026-08-01T10:11:12\n",
    # The file starts with a UTF-8 byte order mark; the header must be clean.
    "bom_start.csv": b"\xef\xbb\xbfa,b\n1,2\n",
    # A data row that contains U+FEFF.  This is not a file BOM and is kept.
    "bom_in_data.csv": b"a,b\n\xef\xbb\xbf1,2\n",
    # A lone 0xFF byte can never appear in valid UTF-8 and must be rejected.
    "bad_utf8.csv": b"a,b\n\xff,2\n",
    # CRLF line endings.
    "crlf.csv": b"a,b\r\n1,2\r\n",
    # A quoted field that contains a line break.
    "embeddednl.csv": b'a,b\n"x\r\ny",2\n',
    # A quoted field that contains an escaped quote.
    "escapedquote.csv": b'a,b\n"say ""hi""",2\n',
    # A quoted value that spells the NULL marker stays a string.
    "quotednull.csv": b'a,b\n"NULL",1\n',
    # Duplicate header names are disambiguated.
    "dupheader.csv": b"a,a\n1,2\n",
    # A row with fewer fields than the header.
    "badlen.csv": b"a,b\n1,2\n3\n",
    # An unterminated quoted field.
    "badquote.csv": b'a,b\n"unterminated,2\n',
    # A header row without any data row.
    "headeronly.csv": b"a,b,c\n",
    # A file with no content at all.
    "empty.csv": b"",
    # A column that is NULL in every row.
    "allnullcol.csv": b"k,v\n,1\n,2\n",
    # The exact bounds of BIGINT.
    "bounds.csv": b"big,small\n9223372036854775807,-9223372036854775808\n",
    # An integer that does not fit into BIGINT; it must stay text.
    "overflow.csv": b"big\n92233720368547758079223372036854775807\n",
    # An integer and a float in the same column widen to a float.
    "widen.csv": b"n,f\n1.5,2.5\n",
    # A custom NULL marker.
    "nullstr.csv": b"a,b\n\\N,2\n",
    # A nested JSON object must be rejected.
    "nested.jsonl": b'{"a":1,"b":{"c":2}}\n',
    # A JSON array must be rejected.
    "array.jsonl": b'{"a":1,"b":[1,2]}\n',
    # A field that is missing from a later record becomes NULL.
    "missing.jsonl": b'{"a":1,"b":"x"}\n{"c":2}\n',
    # The same field holds two different types and widens to text.
    "conflict.jsonl": b'{"a":1,"b":"x"}\n{"a":"str","c":2}\n',
}


def main():
    os.makedirs(TARGET, exist_ok=True)
    for name, content in sorted(FIXTURES.items()):
        with open(os.path.join(TARGET, name), "wb") as handle:
            handle.write(content)
    print("wrote %d fixtures to %s" % (len(FIXTURES), TARGET))


if __name__ == "__main__":
    main()
